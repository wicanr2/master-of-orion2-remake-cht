// OrigTechTopic 查某個科技在原版屬於哪個主題。第二個回傳值為 false 代表查不到
// (超出表的範圍,或原版本來就沒給它歸屬——見 OrigTechTopicTable 的 −1 說明)。
func OrigTechTopic(tech Technology) (ResearchTopic, bool) {
	i := int(tech)
	if i < 0 || i >= len(OrigTechTopicTable) {
		return 0, false
	}
	t := OrigTechTopicTable[i]
	if t < 0 {
		return 0, false
	}
	return ResearchTopic(t), true
}

// OrigTopicIsSelfLoop 回報某個主題的 next 是否指向自己。
//
// 原版用自環表示「這個主題永遠不會被解鎖」:主題要變成可研究,唯一的路是別人的 next
// 指到它;指向自己就等於要先有它才能有它。
//
// ⚠ **這個判斷只在主題 74 身上是乾淨的。** 0 這個值同時是「鏈到此為止」的哨符
// (8 個 Hyper-Advanced 主題的 next 都是 0),所以主題 0 回 true 是巧合而非證據
// ——它不可研究的理由是別的(開局科技的容器,`Init_Player_Tech_` 直接發)。
func OrigTopicIsSelfLoop(topic ResearchTopic) bool {
	i := int(topic)
	if i < 0 || i >= len(OrigTopicNext) {
		return false
	}
	return OrigTopicNext[i] == i
}
