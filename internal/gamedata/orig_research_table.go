// orig_research_table.go:**原版執行檔裡的研究主題表**——用來驗證 `techtree.go` 的轉寫。
//
// ============ 為什麼要有這一份 ============
//
// `techtree.go` 的檔頭寫得很清楚:那 83 列是逐字轉寫自 **openorion2 的 `tech.cpp`**。
// 也就是說,remake 整棵研究樹的成本與可選科技,證據等級一直是**二手**——
// openorion2 讀對了就對,讀錯了 remake 跟著錯,而且沒有任何測試會發現。
//
// 2026-08-07 從原版執行檔把同一張表挖出來,兩邊逐項對了一次。
//
// ============ 表在哪、怎麼解 ============
//
//	主題表 word_17D90C,83 筆,每筆 0x17 = 23 byte
//	  +0  word   下一個主題(完成本主題就把它標成「可研究」)
//	  +2..+9     四個 word 的科技清單 —— **執行檔裡全是 0**,執行期才由科技表反填
//	  +10 dword  研究成本
//	  +14 byte   一個 0..13 的分類值(sub_FC845 拿它跟 0x16 比,未命名)
//
//	科技表 word_17E07F,212 筆,每筆 0x0D = 13 byte
//	  +0  word   這個科技屬於哪個主題
//	  +5  byte   一個閘門旗標(byte_199CB4 開啟時才檢查,未命名)
//
// 欄位的出處都是指令而不是猜的:`Init_Player_Tech_` @ 0x5E55F 的
// `imul ecx, topic, 17h / movsx eax, word_17D90C[ecx]` 給了 +0 與 stride;
// `word_17D90E[topic*17h + i*2]` 給了科技清單的位置;
// `sub_FD335` 的 `mov eax, dword_17D916[eax]` 給了 +10 的成本;
// `sub_5E9B1` 的 `imul eax, tech, 0Dh / mov ax, word_17E07F[eax]` 給了科技表。
//
// ============ 對照結果 ============
//
// | 項目 | 結果 |
// |---|---|
// | 83 個主題的成本 | **74 個完全相同**,9 個有差(全部有解釋,見下) |
// | 主題 → 科技的歸屬 | **81 個主題完全相同**,逐科技 **199 條吻合** |
// | remake 有、原版沒有的科技 | **0 個** |
//
// 199 條科技歸屬全中、而且 remake 沒有多出任何一個科技——**openorion2 的轉寫是對的**。
// 這一份的價值不在改了什麼,而在把整棵樹的證據等級從二手抬到一手驗證過。
//
// ============ 九個不同的,全部有解釋 ============
//
// **八個 Hyper-Advanced 主題(75–82):15000 vs 25000,是真的版本差異。**
// 三份執行檔各查一次:
//
//	1996 原版      → 15000
//	patch 1.31     → 15000(整張表與 1996 版 **byte-identical**)
//	patch 1.50.26  → 25000(只有這 8 筆變,主題 74 仍是 15000)
//
// remake 的 `RuleProfile` 早就寫著 1.3 = 15000、1.5 = 25000,出處是社群的
// `CHANGELOG_150.TXT` 1.50.9「Hyper-Advanced Tech Cost Bug」。現在那兩個數字
// **在三份執行檔裡各自有一手來源**,不再只靠 changelog 的一句話。
//
// **主題 74 XENON TECHNOLOGY:原版表寫 15000,openorion2 寫 0 並註「always unavailable」。**
// 那句註解是對的,而且原版用了一個很乾脆的編碼方式:
//
//	nxt[74] == 74      ← 它的「下一個主題」是**它自己**
//	沒有任何主題的 next 指向 74
//
// 主題要變成可研究,唯一的路是「某個已完成主題的 next 指到它」。指向 74 的只有 74 自己,
// 而那需要先完成 74。**自環就是「永遠解不開」的寫法。** 成本欄位填了 15000 只是沒留白,
// 玩家永遠讀不到它。remake 保持 0,但把那 8 個科技記在 `OrigXenonTechs`——
// 它們是安塔蘭專屬科技,得靠打安塔蘭人拿,不是研究出來的。
//
// 主題 0 STARTING_TECH 同理:`nxt[0] == 0`,清單是每個帝國開局就有的四樣。
//
// ============ 一個順帶對上的地方 ============
//
// `OrigStartingTechs` 裡有 `TECH_PULSE_RIFLE`。remake 的 `GroundRifleTechBonus` 把
// 脈衝步槍定為 **+0 的基準點**,先前的理由只是「它是最低階的那把」。
// 現在有了硬理由:**脈衝步槍在開局科技裡,每個帝國第一回合就有**,所以它必然是零點。

